#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_valid() {
        for font in ["Symbol", "Wingdings", "Wingdings 2", "Wingdings 3", "Webdings"] {
            let t = table(font).unwrap();
            for w in t.windows(2) {
                assert!(w[0].0 < w[1].0, "{font}: {:#X} before {:#X}", w[0].0, w[1].0);
            }
            for (c, u) in t {
                assert!(char::from_u32(*u).is_some(), "{font}: {c:#X}");
                assert!(*c >= 0x20, "{font}: {c:#X}");
            }
        }
    }

    #[test]
    fn tables_are_nearly_complete() {
        // Every code a font defines has an entry, except the few the symbol fonts leave empty.
        assert!(WINGDINGS.len() >= 220, "{}", WINGDINGS.len());
        assert!(WINGDINGS_2.len() >= 200, "{}", WINGDINGS_2.len());
        assert!(WINGDINGS_3.len() >= 200, "{}", WINGDINGS_3.len());
        assert!(WEBDINGS.len() >= 220, "{}", WEBDINGS.len());
        assert!(SYMBOL.len() >= 150, "{}", SYMBOL.len());
    }

    #[test]
    fn well_known_symbols() {
        assert_eq!(map_code("Wingdings", 0x4A), Some('\u{263A}'));
        assert_eq!(map_code("Wingdings", 0xF04A), Some('\u{263A}'));
        assert_eq!(map_code("wingdings", 0xFC), Some('\u{2714}'));
        assert_eq!(map_code("Wingdings", 0xFE), Some('\u{2611}'));
        assert_eq!(map_code("Wingdings", 0x6C), Some('\u{25CF}'));
        assert_eq!(map_code("Wingdings", 0xE0), Some('\u{1F86A}'));
        assert_eq!(map_code("Wingdings 3", 0x22), Some('\u{2192}'));
        assert_eq!(map_code("Webdings", 0x48), Some('\u{1F3E0}'));
        assert_eq!(map_code("Symbol", 0xF0B7), Some('\u{2022}'));
        assert_eq!(map_code("Symbol", 0x61), Some('\u{03B1}'));
        assert_eq!(map_code("Symbol", 0x57), Some('\u{03A9}'));
        assert_eq!(map_code("Symbol", 0xE5), Some('\u{2211}'));
        assert_eq!(map_code("Arial", 0x4A), None);
        assert_eq!(map_code("Wingdings", 0x20), None);
        assert!(is_symbol_font(" Wingdings 2 ") && !is_symbol_font("Calibri"));
    }

    #[test]
    fn maps_a_run() {
        assert_eq!(map_text("Wingdings", "JKL"), "\u{263A}\u{1F610}\u{2639}");
        assert_eq!(map_text("Symbol", "abc 1"), "\u{03B1}\u{03B2}\u{03C7} 1");
        assert_eq!(map_text("Times New Roman", "JKL"), "JKL");
    }
}
