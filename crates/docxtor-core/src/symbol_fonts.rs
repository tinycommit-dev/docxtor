//! Symbol, Wingdings, Wingdings 2, Wingdings 3 and Webdings to Unicode. Word stores text in these fonts as the
//! font's own character codes (`J` or U+F04A for a smiley in Wingdings), so a computer without the font shows
//! the wrong character. Each table maps a code to the Unicode character that looks like the font's glyph. The
//! names in the comments are the glyph names of the fonts. Symbol follows Adobe's Symbol encoding. For the
//! pictographic fonts the match is a look-alike: where Unicode has the same picture it is used, and a few rare
//! glyphs map to the nearest similar character.

/// Whether a font name is one of the symbol fonts (compared without case).
pub fn is_symbol_font(name: &str) -> bool {
    table(name).is_some()
}

/// The Unicode character for a character of a symbol font. `code` is the font's code: 0x20 to 0xFF, or the same
/// in the private use area (0xF020 to 0xF0FF) as Word writes `w:sym`. None when the font isn't a symbol font or
/// the code has no entry (the caller keeps the character).
pub fn map_code(font: &str, code: u32) -> Option<char> {
    let code = if (0xF020..=0xF0FF).contains(&code) { code - 0xF000 } else { code };
    if !(0x20..=0xFF).contains(&code) {
        return None;
    }
    let t = table(font)?;
    let code = code as u8;
    let i = t.binary_search_by_key(&code, |(c, _)| *c).ok()?;
    char::from_u32(t[i].1)
}

/// Map a whole text run of a symbol font, character by character. Characters without an entry stay.
pub fn map_text(font: &str, text: &str) -> String {
    text.chars().map(|c| map_code(font, c as u32).unwrap_or(c)).collect()
}

fn table(font: &str) -> Option<&'static [(u8, u32)]> {
    match font.trim().to_ascii_lowercase().as_str() {
        "symbol" => Some(SYMBOL),
        "wingdings" => Some(WINGDINGS),
        "wingdings 2" => Some(WINGDINGS_2),
        "wingdings 3" => Some(WINGDINGS_3),
        "webdings" => Some(WEBDINGS),
        _ => None,
    }
}

