// deploy/_headers is the one source of Docxtor's security headers and caching rules. Cloudflare Pages reads it as it is; this turns it into
// the same rules for the two web servers people self-host with, so they get exactly what Cloudflare sends:
//   deploy/nginx.conf   location blocks to include inside a `server { }`
//   deploy/Caddyfile    a snippet (`import docxtor-headers`) for a site block
// Both are generated and committed; `--check` (part of `npm test`) fails when they no longer match `_headers`.
//   node scripts/headers.mjs           writes them
//   node scripts/headers.mjs --check   exits 1 when they are stale
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * The rules of a `_headers` file: a path pattern (`*` matches anything), then its indented lines: `Name: value`, or `! Name` to detach a
 * header an earlier rule set (what Cloudflare Pages calls detaching). A detach is kept as [name, null].
 */
export function parseHeaders(text) {
  const rules = [];
  let cur = null;
  for (const raw of text.split("\n")) {
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    if (!/^\s/.test(raw)) {
      cur = { pattern: raw.trim(), headers: [] };
      rules.push(cur);
    } else if (cur) {
      if (/^\s*!\s*\S+\s*$/.test(raw)) {
        cur.headers.push([raw.trim().slice(1).trim(), null]);
        continue;
      }
      const i = raw.indexOf(":");
      if (i < 0) throw new Error(`_headers: not a "Name: value" line: ${raw}`);
      cur.headers.push([raw.slice(0, i).trim(), raw.slice(i + 1).trim()]);
    } else {
      throw new Error(`_headers: a header before any path: ${raw}`);
    }
  }
  return rules;
}

/** A pattern as a regular expression, the way Cloudflare reads it: `*` matches anything. */
export function patternRegExp(pattern) {
  return new RegExp(`^${pattern.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*")}$`);
}

/** How a pattern matches: everything (`/*`), a folder and what is under it (`/assets/*`) or exactly one path. Anything else is not supported. */
export function patternKind(pattern) {
  if (pattern === "/*") return { kind: "all" };
  if (/^\/[^*]*\/\*$/.test(pattern)) return { kind: "prefix", path: pattern.slice(0, -1) };
  if (/^\/[^*]*$/.test(pattern)) return { kind: "exact", path: pattern };
  throw new Error(`_headers: the pattern ${pattern} is not supported (use /*, /folder/* or an exact path)`);
}

/**
 * What Cloudflare Pages sends for a path: every rule that matches adds its headers, in file order; two values for one name are joined
 * with ", " (so two Content-Security-Policy values are two policies, and the browser enforces both); `! Name` removes what the rules
 * before it set. A rule that wants to replace a value says so with a detach first, then the new value.
 */
export function mergeHeaders(ruleHeaders) {
  const merged = new Map();
  for (const [name, value] of ruleHeaders) {
    const key = name.toLowerCase();
    if (value === null) merged.delete(key);
    else merged.set(key, merged.has(key) ? { name: merged.get(key).name, value: `${merged.get(key).value}, ${value}` } : { name, value });
  }
  return [...merged.values()].map((h) => [h.name, h.value]);
}

/** The headers every path of a rule's pattern gets: the rules that cover the whole pattern (the general ones, itself, a folder around it), in file order. */
export function effectiveHeaders(rules, pattern) {
  const mine = patternKind(pattern);
  const covers = (r) => {
    const k = patternKind(r.pattern);
    if (k.kind === "all") return true;
    if (r.pattern === pattern) return true;
    return k.kind === "prefix" && mine.kind !== "all" && mine.path.startsWith(k.path);
  };
  return mergeHeaders(rules.filter(covers).flatMap((r) => r.headers));
}

const BANNER = (comment) =>
  [
    "Generated by scripts/headers.mjs from deploy/_headers, the one source of Docxtor's security headers and caching rules.",
    "Do not edit by hand: change deploy/_headers, then run `node scripts/headers.mjs`. `npm test` fails when this file is stale.",
  ].map((l) => `${comment} ${l}`);

function nginxValue(v) {
  if (/["\\$]/.test(v)) throw new Error(`_headers: a value nginx cannot quote safely: ${v}`);
  return `"${v}"`;
}

/** nginx: one `location` per rule, each repeating the headers of the rules that cover it (nginx does not inherit `add_header` into a block that has its own). */
export function toNginx(rules) {
  const blocks = [];
  const specific = rules.filter((r) => patternKind(r.pattern).kind !== "all");
  const all = rules.find((r) => patternKind(r.pattern).kind === "all");
  const order = { exact: 0, prefix: 1 };
  const sorted = [...specific].sort((a, b) => order[patternKind(a.pattern).kind] - order[patternKind(b.pattern).kind]);
  const emit = (selector, pattern) =>
    `location ${selector} {\n${effectiveHeaders(rules, pattern)
      .map(([k, v]) => `    add_header ${k} ${nginxValue(v)} always;`)
      .join("\n")}\n}`;
  for (const r of sorted) {
    const k = patternKind(r.pattern);
    blocks.push(emit(k.kind === "exact" ? `= ${k.path}` : `^~ ${k.path}`, r.pattern));
  }
  if (all) blocks.push(emit("/", all.pattern));
  return [
    ...BANNER("#"),
    "#",
    "# Include this inside a `server { }` that serves the built files from its `root`:  include /etc/nginx/docxtor-headers.conf;",
    "# (the path is wherever you put the file). The last block, `location /`, gives every other file the security headers.",
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

function caddyValue(v) {
  if (/["\\]/.test(v)) throw new Error(`_headers: a value the Caddyfile cannot quote safely: ${v}`);
  return `"${v}"`;
}

/** Caddy: a snippet with one `header` block for everything and one per path rule. */
export function toCaddy(rules) {
  const lines = [
    ...BANNER("#"),
    "#",
    "# Put this file next to your Caddyfile and, in your site block (with `root * /srv/docxtor` and `file_server`):",
    "#     import docxtor-headers",
    "",
    "(docxtor-headers) {",
  ];
  const all = rules.find((r) => patternKind(r.pattern).kind === "all");
  const body = (hs) => hs.map(([k, v]) => `\t\t${k} ${caddyValue(v)}`);
  const base = all ? mergeHeaders(all.headers) : [];
  if (all) lines.push("\theader {", ...body(base), "\t}");
  let n = 0;
  for (const r of rules) {
    const k = patternKind(r.pattern);
    if (k.kind === "all") continue;
    const name = `docxtor_${++n}`;
    lines.push("", `\t@${name} path ${k.kind === "prefix" ? `${k.path}*` : k.path}`);
    // Caddy's `header Name "value"` sets (replaces) the header, so a block says only what differs from the general block: new or changed
    // values, and `-Name` for a header this path does not send. Blocks run in file order, a more specific one after the general ones.
    const effective = effectiveHeaders(rules, r.pattern);
    const extra = effective.filter(([key, v]) => !base.some(([k2, v2]) => k2.toLowerCase() === key.toLowerCase() && v2 === v));
    const gone = base.filter(([k2]) => !effective.some(([key]) => key.toLowerCase() === k2.toLowerCase()));
    lines.push(`\theader @${name} {`, ...body(extra), ...gone.map(([k2]) => `\t\t-${k2}`), "\t}");
  }
  lines.push("}", "");
  return lines.join("\n");
}

export const OUTPUTS = [
  { file: "deploy/nginx.conf", make: toNginx },
  { file: "deploy/Caddyfile", make: toCaddy },
];

export function generate(dir = root) {
  const rules = parseHeaders(readFileSync(join(dir, "deploy/_headers"), "utf8"));
  return OUTPUTS.map((o) => ({ file: o.file, text: o.make(rules) }));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const { file, text } of generate()) {
    const path = join(root, file);
    if (check) {
      if (!existsSync(path) || readFileSync(path, "utf8") !== text) {
        console.error(`${file} does not match deploy/_headers: run  node scripts/headers.mjs`);
        stale = true;
      }
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${file}`);
    }
  }
  if (check) {
    if (stale) process.exit(1);
    console.log("deploy/nginx.conf and deploy/Caddyfile match deploy/_headers");
  }
}
